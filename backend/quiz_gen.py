"""AI-generated quiz question service.

Uses Claude Sonnet 4.5 (Emergent LLM key) to generate on-the-fly quiz
questions when the user wants more. Returns a JSON array of questions
matching the app's quiz shape: {q, opts[4], correct, exp}.
"""
from __future__ import annotations

import json
import os
import re
import uuid
from emergentintegrations.llm.chat import LlmChat, UserMessage

_PROMPT = """You are a tax-quiz question generator for the TaxQuest app.

Generate exactly {count} multiple-choice quiz questions about the topic below.
Topic: {topic}
Level: {level}  (beginner | intermediate | pro)

Return ONLY valid minified JSON — no markdown fences, no commentary — matching this shape:
[
  {{
    "q": "clear, factual question ending with ?",
    "opts": ["opt A","opt B","opt C","opt D"],
    "correct": 0,
    "exp": "one-sentence explanation of why the answer is correct"
  }}
]

Rules:
- Exactly 4 options per question.
- "correct" is the 0-based index of the right option.
- Keep each question under 160 characters.
- Base facts on FY 2024-25 / 2026 baselines.
- Avoid duplicates.
- Never include markdown, code fences, or trailing commas.
"""


def _clean(raw: str) -> str:
    raw = raw.strip()
    # strip ```json ... ``` fences if any
    fenced = re.match(r"^```(?:json)?\s*(.*?)```\s*$", raw, re.DOTALL | re.IGNORECASE)
    if fenced:
        raw = fenced.group(1).strip()
    # take from first "[" to last "]"
    i, j = raw.find("["), raw.rfind("]")
    if i != -1 and j != -1 and j > i:
        raw = raw[i : j + 1]
    return raw


def _validate(items):
    out = []
    for it in items:
        if not isinstance(it, dict):
            continue
        q = str(it.get("q", "")).strip()
        opts = it.get("opts")
        correct = it.get("correct")
        exp = str(it.get("exp", "")).strip()
        if not q or not isinstance(opts, list) or len(opts) != 4:
            continue
        opts = [str(o).strip() for o in opts]
        if any(not o for o in opts):
            continue
        try:
            correct = int(correct)
        except (TypeError, ValueError):
            continue
        if correct < 0 or correct > 3:
            continue
        out.append({"q": q, "opts": opts, "correct": correct, "exp": exp or "Generated by TaxQuest AI."})
    return out


async def generate_questions(topic: str, level: str, count: int) -> list[dict]:
    count = max(1, min(int(count or 5), 8))
    level = (level or "beginner").lower()
    if level not in {"beginner", "intermediate", "pro"}:
        level = "beginner"

    chat = LlmChat(
        api_key=os.environ["EMERGENT_LLM_KEY"],
        session_id=f"gen-{uuid.uuid4().hex[:10]}",
        system_message="You return ONLY valid JSON — never prose, never markdown.",
    ).with_model("anthropic", "claude-sonnet-4-5-20250929")

    reply = await chat.send_message(
        UserMessage(text=_PROMPT.format(topic=topic, level=level, count=count))
    )
    text = getattr(reply, "text", None) or getattr(reply, "content", None) or str(reply)
    try:
        parsed = json.loads(_clean(text))
    except Exception:
        # one salvage attempt — trim to last valid closing brace
        cleaned = _clean(text)
        parsed = json.loads(cleaned[: cleaned.rfind("}") + 1] + "]") if "}" in cleaned else []

    if isinstance(parsed, dict):
        parsed = parsed.get("questions") or parsed.get("items") or []

    return _validate(parsed if isinstance(parsed, list) else [])
